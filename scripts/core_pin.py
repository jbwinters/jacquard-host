GENERATED = {
    "src/jacquard_host/compat.py": render_python,
    "typescript/src/compat.ts": render_typescript,
    "go/protocol/compat.go": render_go,
    "rust/src/compat.rs": render_rust,
    "java/src/main/java/org/jacquardlang/host/Compat.java": render_java,
}
BLOCKS = {
    "docs/COMPATIBILITY.md": render_compatibility,
}


def replace_block(text: str, body: str, name: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise PinError(f"{name}: missing core-pin markers")
    return text[:start + len(BEGIN)] + "\n" + body + text[end:]


def expected_files(pin: dict, root: Path = REPO) -> dict[str, str]:
    files = {name: render(pin) for name, render in GENERATED.items()}
    for name, render in BLOCKS.items():
        files[name] = replace_block((root / name).read_text(encoding="utf-8"), render(pin), name)
    return files


def problems(pin: dict, root: Path = REPO) -> list[str]:
    found: list[str] = []
    for name, text in expected_files(pin, root).items():
        path = root / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            found.append(f"{name} is out of date; run scripts/core_pin.py sync")
    kit_dirs = [root / directory.relative_to(REPO) for directory in KIT_DIRS]
    for kit_dir in kit_dirs:
        label = kit_dir.relative_to(root)
        for name in KIT_FILES:
            path = kit_dir / name
            observed = sha256(path.read_bytes()) if path.exists() else "missing"
            if observed != pin["kit"]["digests"][name]:
                found.append(f"vendored {label}/{name}: sha256 {observed} is not the pinned {pin['kit']['digests'][name]}")
        for name in KIT_EXTRAS:
            first, copy = kit_dirs[0] / name, kit_dir / name
            if not copy.exists() or copy.read_bytes() != first.read_bytes():
                found.append(f"vendored {label}/{name} differs from {kit_dirs[0].relative_to(root)}/{name}")
    if not found:
        manifest = json.loads((kit_dirs[0] / "kit/kit.json").read_text(encoding="utf-8"))
        found += manifest_problems(manifest, pin)
    return found


def manifest_problems(manifest: dict, pin: dict) -> list[str]:
    found = []
    for field, expected in (("protocol", pin["protocol"]), ("carrier", pin["carrier"]),
                            ("core_version", pin["release"]["version"])):
        if manifest.get(field) != expected:
            found.append(f"kit.json {field} {manifest.get(field)!r} is not the pinned {expected!r}")
    pending = decision_names(manifest)
    if pending != pin["kit"]["pending_decisions"]:
        found.append(f"kit.json pending decisions {pending} are not the pinned {pin['kit']['pending_decisions']}")
    return found


def decision_names(manifest: dict) -> list[str]:
    """Return the kit's pending decision names, refusing a malformed list."""
    entries = manifest.get("pending_decisions", [])
    if not isinstance(entries, list) or not all(isinstance(entry, dict) and isinstance(entry.get("name"), str) for entry in entries):
        raise PinError("kit.json pending_decisions must be a list of objects with a string name")
    return [entry["name"] for entry in entries]


def sync(pin: dict, root: Path = REPO) -> list[str]:
    """Rewrite out-of-date generated files through staged renames."""
    changed = {}
    for name, text in expected_files(pin, root).items():
        path = root / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            changed[name] = text
    write_files({root / name: text.encode("utf-8") for name, text in changed.items()})
    return list(changed)


# --- network ---------------------------------------------------------------

def fetch(url: str, *, api: bool = False, limit: int = 256 * 1024 * 1024) -> bytes:
    headers = {"User-Agent": "jacquard-host-core-pin"}
    if api:
        headers["Accept"] = "application/vnd.github+json"
        token = os.environ.get("GITHUB_TOKEN")
        if token:
            headers["Authorization"] = f"Bearer {token}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as response:
        data = response.read(limit + 1)
    if len(data) > limit:
        raise PinError(f"{url}: response exceeds {limit} bytes")
    return data


def api(pin_repository: str, path: str) -> dict:
    return json.loads(fetch(f"https://api.github.com/repos/{pin_repository}/{path}", api=True))


def platform_key() -> str:
    system = {"Linux": "linux", "Darwin": "macos"}.get(platform.system())
    machine = {"x86_64": "x86_64", "amd64": "x86_64", "arm64": "arm64", "aarch64": "arm64"}.get(platform.machine().lower())
    if not system or not machine:
        raise PinError(f"no Core release asset for {platform.system()} {platform.machine()}; build the pinned commit from source (docs/SETUP.md)")
    return f"{system}-{machine}"


def check_members(archive: tarfile.TarFile, root: Path, name: str) -> None:
    """Refuse members or link targets that would land outside root."""
    base = root.resolve()
    for member in archive.getmembers():
        target = (base / member.name).resolve()
        if not target.is_relative_to(base) or not (member.isfile() or member.isdir() or member.issym()):
            raise PinError(f"{name}: refusing archive member {member.name}")
        # Links may only name a sibling entry, so no chain of them can leave its
        # directory; this does not depend on the tarfile data filter.
        if member.issym() and not re.fullmatch(r"[0-9A-Za-z_][0-9A-Za-z._-]*", member.linkname):
            raise PinError(f"{name}: refusing link {member.name} -> {member.linkname}")


def release_env(prefix: Path) -> dict[str, str]:
    # Point at the real executable, not the sh launcher, so SDK cache keys cover its bytes.
    return {
        "JACQUARD_BIN": str(prefix / "libexec" / "jacquard" / "jacquard"),
        "JACQUARD_PRELUDE": str(prefix / "share" / "jacquard" / "prelude"),
        "JACQUARD_RUNTIME": str(prefix / "share" / "jacquard" / "runtime"),
    }


def only_directory(root: Path) -> Path:
    entries = [path for path in root.iterdir() if path.name != ".verified-sha256"]
    if len(entries) != 1 or not entries[0].is_dir():
        raise PinError(f"{root}: expected one extracted release directory")
    return entries[0]


def check_version(env: dict[str, str], version: str) -> None:
    result = subprocess.run([env["JACQUARD_BIN"], "--version"], capture_output=True, text=True, timeout=30,
                            env={**os.environ, **env})
    if result.returncode or result.stdout.strip().split()[-1:] != [version]:
        raise PinError(f"installed Core reports {result.stdout.strip()!r}, not {version}")


def install(pin: dict, dest: Path, key: str | None = None) -> dict[str, str]:
    key = key or platform_key()
    asset = pin["assets"].get(key)
    if not asset:
        raise PinError(f"{pin['release']['tag']} has no {key} asset; build the pinned commit from source (docs/SETUP.md)")
    root = dest / f"{pin['release']['tag']}-{key}"
    marker = root / ".verified-sha256"
    if marker.exists() and marker.read_text().strip() == asset["sha256"]:
        env = release_env(only_directory(root))
        check_version(env, pin["release"]["version"])
        return env
    if not hasattr(tarfile, "data_filter"):
        raise PinError("safe archive extraction needs Python 3.11.4 or later (tarfile data filter)")
    url = f"https://github.com/{pin['repository']}/releases/download/{pin['release']['tag']}/{asset['name']}"
    data = fetch(url)
    if sha256(data) != asset["sha256"]:
        raise PinError(f"{asset['name']}: sha256 {sha256(data)} is not the pinned {asset['sha256']}")
    dest.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{root.name}-", dir=dest))
    try:
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
            check_members(archive, staging, asset["name"])
            archive.extractall(staging, filter="data")
        prefix = only_directory(staging)
        check_version(release_env(prefix), pin["release"]["version"])
        (staging / ".verified-sha256").write_text(asset["sha256"] + "\n")
        if root.exists():
            shutil.rmtree(root)
        staging.rename(root)
    finally:
        shutil.rmtree(staging, ignore_errors=True)
    return release_env(only_directory(root))


def exports(env: dict[str, str]) -> str:
    return "".join(f"export {key}={shlex.quote(value)}\n" for key, value in env.items())


def parse_sha256(text: str, name: str) -> str:
    for line in text.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[1].lstrip("*") == name and re.fullmatch(r"[0-9a-f]{64}", parts[0]):
            return parts[0]
    raise PinError(f"no sha256 for {name} in its checksum file")


def release_assets(repository: str, tag: str) -> dict:
    release = api(repository, f"releases/tags/{tag}")
    by_name = {asset["name"]: asset["browser_download_url"] for asset in release["assets"]}
    assets = {}
    for name in sorted(by_name):
        match = re.fullmatch(r"jacquard-([a-z]+-[a-z0-9_]+)\.tar\.gz", name)
        if match and f"{name}.sha256" in by_name:
            digest = parse_sha256(fetch(by_name[f"{name}.sha256"]).decode(), name)
            assets[match.group(1)] = {"name": name, "sha256": digest}
    if not assets:
        raise PinError(f"{tag} publishes no checksummed binary assets")
    return assets


def tag_commit(repository: str, tag: str, checkout: Path | None) -> str:
    if checkout:
        return subprocess.run(["git", "-C", str(checkout), "rev-parse", f"{tag}^{{commit}}"],
                              check=True, capture_output=True, text=True).stdout.strip()
    ref = api(repository, f"git/ref/tags/{tag}")["object"]
    while ref["type"] == "tag":
        ref = api(repository, f"git/tags/{ref['sha']}")["object"]
    return ref["sha"]


def kit_file(repository: str, commit: str, path: str, checkout: Path | None) -> bytes:
    if checkout:
        return subprocess.run(["git", "-C", str(checkout), "show", f"{commit}:{path}"],
                              check=True, capture_output=True).stdout
    return fetch(f"https://raw.githubusercontent.com/{repository}/{commit}/{path}")


def update(pin: dict, tag: str, checkout: Path | None, kit_dirs: tuple[Path, ...] = KIT_DIRS) -> dict:
    if not re.fullmatch(re.escape(TAG_PREFIX) + VERSION, tag):
        raise PinError(f"release tags are {TAG_PREFIX}X.Y.Z, not {tag!r}")
    repository = pin["repository"]
    commit = tag_commit(repository, tag, checkout)
    files = {name: kit_file(repository, commit, f"{pin['kit']['path']}/{name}", checkout)
             for name in (*KIT_FILES, *KIT_EXTRAS)}
    manifest = json.loads(files["kit/kit.json"])
    new = json.loads(json.dumps(pin))
    new["release"] = {"tag": tag, "version": tag.removeprefix(TAG_PREFIX), "commit": commit}
    new["kit"]["digests"] = {name: sha256(files[name]) for name in KIT_FILES}
    new["kit"]["pending_decisions"] = decision_names(manifest)
    if manifest.get("protocol") != pin["protocol"] or manifest.get("carrier") != pin["carrier"]:
        raise PinError(f"{tag} ships protocol {manifest.get('protocol')} / {manifest.get('carrier')}; "
                       "a protocol change needs adapter work, not a pin refresh")
    found = manifest_problems(manifest, new)
    if found:
        raise PinError("; ".join(found))
    new["assets"] = release_assets(repository, tag)
    if "linux-x86_64" not in new["assets"]:
        raise PinError(f"{tag} has no linux-x86_64 asset, which CI installs")
    validate(new)
    write_files({directory / name: data for directory in kit_dirs for name, data in files.items()})
    return new


def write_kit(files: dict[str, bytes], kit_dir: Path) -> None:
    """Replace every kit file through staged renames, restoring all on failure."""
    write_files({kit_dir / name: data for name, data in files.items()})


def write_files(contents: dict[Path, bytes]) -> None:
    """Replace files through staged renames. On failure, restore the originals
    and raise the original error; secondary failures are warnings."""
    originals = {path: path.read_bytes() if path.exists() else None for path in contents}
    staged = []
    try:
        for path, data in contents.items():
            temporary = path.with_name(f".{path.name}.core-pin")
            staged.append((temporary, path))
            temporary.write_bytes(data)
        for temporary, path in staged:
            temporary.replace(path)
    except BaseException:
        remove_temporaries(staged)
        restore(originals)
        raise
    remove_temporaries(staged)


def remove_temporaries(staged: list[tuple[Path, Path]]) -> None:
    """Best-effort removal of staged files, warning about each one left behind."""
    for temporary, _ in staged:
        try:
            temporary.unlink(missing_ok=True)
        except OSError as error:
            warn(f"could not remove temporary file {temporary}: {error}")


def restore(originals: dict[Path, bytes | None]) -> bool:
    """Restore every changed file, warning about each that cannot be restored.
    One failure does not stop the others. Returns whether all were restored."""
    complete = True
    for path, data in originals.items():
        try:
            current = path.read_bytes() if path.exists() else None
            if current == data:
                continue
            if data is None:
                path.unlink()
            else:
                path.write_bytes(data)
        except OSError as error:
            complete = False
            warn(f"could not restore {path}: {error}")
    if not complete:
        warn("the restore is incomplete; run `python3 scripts/core_pin.py check` and repair the files named above")
    return complete


def adopt(pin: dict, tag: str, checkout: Path | None, *, root: Path = REPO,
          pin_path: Path = PIN, kit_dirs: tuple[Path, ...] = KIT_DIRS) -> list[str]:
    """Adopt a release: vendor its kit, write the pin, regenerate files.

    Any failure after the kit is written restores the kit, the pin, and the
    generated files and raises the original error; files that cannot be
    restored are reported as warnings.
    """
    generated = [root / name for name in (*GENERATED, *BLOCKS)]
    kit_paths = [directory / name for directory in kit_dirs for name in (*KIT_FILES, *KIT_EXTRAS)]
    originals = {path: path.read_bytes() if path.exists() else None for path in [pin_path, *generated, *kit_paths]}
    new = update(pin, tag, checkout, kit_dirs)
    try:
        write_files({pin_path: dump(new).encode()})
        return sync(new, root)
    except BaseException:
        restore(originals)
        raise


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("check", help="fail if generated files, docs, or the vendored kit drift from the pin")
    commands.add_parser("sync", help="rewrite generated files and documentation blocks from the pin")
    get = commands.add_parser("get", help="print one dotted pin field, for scripts")
    get.add_argument("field")
    inst = commands.add_parser("install", help="download, verify, and unpack the pinned release binary")
    inst.add_argument("--dest", type=Path, default=REPO / ".scratch" / "jacquard-core")
    inst.add_argument("--platform", help="asset key such as linux-x86_64 (default: this machine)")
    inst.add_argument("--github-env", action="store_true", help="append the variables to $GITHUB_ENV")
    commands.add_parser("status", help="compare the pin with Core's latest release (exit 3 if newer)")
    upd = commands.add_parser("update", help="adopt a Core release tag: kit, digests, assets, generated files")
    upd.add_argument("--tag", required=True)
    upd.add_argument("--core-checkout", type=Path, help="read the tag and kit from a local jacquard-lang clone")
    args = parser.parse_args(argv)
    try:
        pin = load()
        if args.command == "check":
            found = problems(pin)
            for problem in found:
                print(problem, file=sys.stderr)
            if not found:
                print(f"pin {pin['release']['tag']} ({pin['release']['commit'][:12]}) is consistent")
            return 1 if found else 0
        if args.command == "sync":
            for name in sync(pin):
                print(f"updated {name}")
            return 0
        if args.command == "get":
            value = pin
            for part in args.field.split("."):
                value = value[part]
            print(value if isinstance(value, str) else json.dumps(value))
            return 0
        if args.command == "install":
            env = install(pin, args.dest.resolve(), args.platform)
            if args.github_env:
                if any("\n" in value for value in env.values()):
                    raise PinError("install paths must not contain newlines")
                with open(os.environ["GITHUB_ENV"], "a", encoding="utf-8") as handle:
                    handle.writelines(f"{key}={value}\n" for key, value in env.items())
            print(exports(env), end="")
            return 0
        if args.command == "status":
            latest = api(pin["repository"], "releases/latest")["tag_name"]
            if latest == pin["release"]["tag"]:
                print(f"pinned {latest} is Core's latest release")
                return 0
            print(f"pinned {pin['release']['tag']}; Core's latest release is {latest}. "
                  f"Adopt it with: python3 scripts/core_pin.py update --tag {latest}")
            return 3
        changed = adopt(pin, args.tag, args.core_checkout)
        for name in changed:
            print(f"updated {name}")
        print(f"pinned {args.tag}. Now run the offline and live suites for every adapter (CONTRIBUTING.md).")
        return 0
    except (PinError, KeyError, OSError, tarfile.TarError, subprocess.CalledProcessError, json.JSONDecodeError) as error:
        print(f"core_pin: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
